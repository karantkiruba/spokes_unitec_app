@frappe.whitelist(allow_guest=True)
def open_cumulative_report(name, items, no_letterhead = 0):
	import json
	output = PdfFileWriter()
	items = json.loads(items)
	empcode = frappe.get_value('Employee',{"user_id": frappe.session.user} )
	employee =frappe.get_doc("Employee", empcode)

	for i, item in enumerate(items):
		total = len(items)
		frappe.publish_realtime("print_so_cumulative", dict(progress=[i+1, total]), user=frappe.session.user)
		item = frappe._dict(item)
		if item.production_drawings:
			fname = item.production_drawings
			file_path = get_files_path(*fname.split("/private/files/", 1)[1].split("/"), is_private=1)
			with open(file_path, "rb") as fileobj:
				filedata = fileobj.read()

			reader = PdfFileReader(io.BytesIO(filedata), strict=False)
			filetomerge = get_watermark_pdf(employee, name, item, mode = "Portrait")
			watermark_file = PdfFileReader(io.BytesIO(filetomerge), strict = False)
			watermark_page = watermark_file.getPage(0)

			filetomerge_l = get_watermark_pdf(employee, name, item, mode = "Landscape")
			watermark_file_l = PdfFileReader(io.BytesIO(filetomerge_l), strict = False)
			watermark_page_l = watermark_file_l.getPage(0)

			for page in reader.pages:
				if page.mediaBox.getWidth() > 600:
					page.mergePage(watermark_page_l)
				else:
					page.mergePage(watermark_page)
				output.addPage(page)

			#output.appendPagesFromReader(reader)
	fname = os.path.join("/tmp", "frappe-pdf-{0}.pdf".format(frappe.generate_hash()))
	output.write(open(fname,"wb"))
	return fname

