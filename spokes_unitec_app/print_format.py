def get_watermark_pdf(employee, name, item, mode):
	today = now_datetime()
	body= """
	<html>
	<head>
		<meta name="pdfkit-orientation" content="{0}"/>
	</head>
	</html>
	""".format(mode)

	footer = """
    <html>
	<head>
		<meta name="pdfkit-orientation" content="{6}"/>
	</head>
	<body>
	<table style='width:100%; font-size:12px; color: red'>
	<tbody>
	<tr>
	<td>Security Level: CONFIDENTIAL</td>
	<td>Printed By: {0}</td>
	<td>Date: {5}</td>
	<td>Sales Order : {1} # {4}</td>
	<td>Qty: {3} Nos</td>
	<td>{2}
	</tr>
	</tbody>
	</table>
	</body>
    </html>
    """.format(employee.employee_name, name, item.item_code, item.quantity, item.spokes_line_item_no, today.strftime('%d/%m/%Y'), mode)

	fname = os.path.join("/tmp", "frappe-pdf-{0}.html".format(frappe.generate_hash()))
	with open(fname, "wb") as f:
		f.write(footer.encode("utf-8"))
		
	options = {}
	options["margin-bottom"] = "5mm"
	options["footer-html"] = fname

	filedata = pdfkit.from_string(body, False, options=options)
	return filedata

